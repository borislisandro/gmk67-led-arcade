"""Lights Out: pressing a key toggles it and every key touching it. Switch the
whole keyboard off. Puzzles are generated by scrambling a dark board with random
presses, so every level is guaranteed to be solvable."""
from __future__ import annotations

from ..color import Frame, hsv
from ..input import KeyEvent
from .base import Game


class LightsOut(Game):
    name = "lightsout"
    title = "Lights Out"
    blurb = "each press flips a key and its neighbours — turn everything off"
    controls = "Press any key to flip it and its neighbours"
    all_keys = True

    def reset(self, now: float) -> None:
        self.level = 1
        self.moves = 0
        self.board = [k for k in self.cells if k != "ESC"]
        self.adj = {k: [n for n in self.layout.neighbours(k) if n in self.board] for k in self.board}
        self.new_puzzle(now)

    def new_puzzle(self, now: float) -> None:
        self.lit: set[str] = set()
        presses = self.rng.sample(self.board, min(len(self.board), 2 + self.level))
        for k in presses:
            self.flip(k)
        if not self.lit:                       # scramble cancelled itself out
            self.new_puzzle(now)
            return
        self.solved_at: float | None = None
        self.hue = self.rng.random()

    def flip(self, k: str) -> None:
        self.lit ^= {k, *self.adj[k]}

    def on_key(self, ev: KeyEvent, now: float) -> None:
        if not ev.pressed or ev.key not in self.adj or self.solved_at is not None:
            return
        self.flip(ev.key)
        self.moves += 1
        if not self.lit:
            self.score = self.level
            self.solved_at = now
            self.emit("win")

    def update(self, now: float) -> None:
        if self.solved_at is not None and now - self.solved_at > 1.5:
            self.level += 1
            self.new_puzzle(now)

    def render(self, now: float) -> Frame:
        if self.solved_at is not None:
            t = now - self.solved_at
            return {k: hsv(self.layout[k].cx / 16 + t) for k in self.board}
        return {k: hsv(self.hue + self.layout[k].cx / 64, 0.85) for k in self.lit}

    def status(self) -> list[str]:
        return [f"Level: {self.level}   Lit keys: {len(self.lit)}   Moves: {self.moves}"]
